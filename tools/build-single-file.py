#!/usr/bin/env python3
"""
tools/build-single-file.py
---------------------------------------------------------------------------
Builds wordpress/single-file.html: the entire calculator (markup + CSS + JS)
in one paste-ready file for a WordPress "Custom HTML" block.

Design rules enforced here:
  • Only the widget markup and the methodology section are copied out of
    index.html — never the <head>, the demo wrapper, or demo-page.css.
  • CSS comes from rt-tokens.css + rt-calc.css, which are already scoped to
    .rt-calc / .rt-methodology, so nothing can leak into the host theme.
  • JS is the same IIFE used in production; it self-initialises and is
    idempotent, so it survives being injected after DOMContentLoaded.
  • The output is deterministic — `tests/build.test.js` rebuilds it and fails
    if the committed artefact has drifted from the sources.

Usage:  python3 tools/build-single-file.py
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "wordpress" / "single-file.html"


def extract_element(html: str, opener_regex: str) -> str:
    """Return the full outer HTML of the element whose opening tag matches."""
    match = re.search(opener_regex, html)
    if not match:
        raise SystemExit(f"opening tag not found: {opener_regex}")

    tag = re.match(r"<(\w[\w-]*)", match.group(0)).group(1)
    start = match.start()
    # Walk forward counting open/close tags of this element name.
    token = re.compile(r"<(/?)%s\b" % re.escape(tag), re.IGNORECASE)
    depth = 0
    for t in token.finditer(html, start):
        depth += -1 if t.group(1) else 1
        if depth == 0:
            end = html.index(">", t.start()) + 1
            return html[start:end].strip()
    raise SystemExit(f"unbalanced <{tag}> element")


def strip_blank_runs(text: str) -> str:
    """Collapse 3+ blank lines so the artefact stays readable."""
    return re.sub(r"\n{3,}", "\n\n", text)


def main() -> None:
    index_html = (ROOT / "index.html").read_text(encoding="utf-8")

    # The opener must be followed by a newline: that rules out the same tag
    # text mentioned inside the WordPress guide comment near the top of the file.
    calculator = extract_element(index_html, r'<div class="rt-calc"[^>]*>\s*\n')
    methodology = extract_element(index_html, r'<section class="rt-methodology"[^>]*>\s*\n')

    # Guard rails: fail loudly if the wrong node was picked up.
    assert calculator.startswith('<div class="rt-calc"'), calculator[:80]
    assert methodology.startswith('<section class="rt-methodology"'), methodology[:80]
    assert calculator.count("<section") <= 3, "calculator block contains unexpected sections"

    tokens_css = (ROOT / "assets/css/rt-tokens.css").read_text(encoding="utf-8").strip()
    calc_css = (ROOT / "assets/css/rt-calc.css").read_text(encoding="utf-8").strip()
    calc_js = (ROOT / "assets/js/rt-calc.js").read_text(encoding="utf-8").strip()

    # The <script> body must not contain the literal closing tag.
    assert "</script" not in calc_js.lower(), "rt-calc.js contains a </script> sequence"

    template = f"""<!--
  ============================================================================
  SMART ERGONOMIC BUDGET CALCULATOR — SINGLE-FILE BUILD
  ============================================================================
  Generated by tools/build-single-file.py — do not edit by hand.
  Rebuild with:  python3 tools/build-single-file.py

  HOW TO USE (WordPress → Custom HTML block)
  ---------------------------------------------------------------------------
  1. Add a "Custom HTML" block to the page you want the calculator on.
  2. Paste this entire file in. It is self-contained: no external CSS or JS.
  3. Click Preview. The widget initialises on its own.

  BEFORE YOU PUBLISH
  ---------------------------------------------------------------------------
  • Replace the 27 placeholder Amazon links — see wordpress/REPLACE-THIS.md.
  • Add the canonical URL to the page (WordPress normally sets it; if you use
    an SEO plugin, set it there rather than pasting a <link> in this block).
  • Do NOT include the JSON-LD blocks from index.html inside this block: put
    schema in <head> via your theme/SEO plugin, and only once per URL.

  SCOPE / SAFETY
  ---------------------------------------------------------------------------
  • Every CSS rule is nested under .rt-calc or .rt-methodology (the token block
    targets those two selectors, never :root). Nothing leaks into your theme.
  • The <style> block has no body/html/global element selectors.
  • The <script> is a single IIFE — it declares no globals except
    window.RT_Calculator, and it is safe to load twice.
  • Paste this block once per page. Two copies would duplicate element IDs.

  TRADE-OFF
  ---------------------------------------------------------------------------
  A single file cannot be cached by the browser separately from the page, so
  the CSS/JS is re-downloaded on every page view and inline scripts are blocked
  by a strict Content-Security-Policy. For production traffic prefer the
  enqueue method in wordpress/functions-snippet.php.
  ============================================================================
-->
<div class="rt-embed">

  <style>
/* ===== 1. Design tokens (scoped to .rt-calc / .rt-methodology) ============ */
{tokens_css}

/* ===== 2. Components (scoped) ============================================= */
{calc_css}
  </style>

  <!-- ===================== WIDGET MARKUP ===================== -->
{calculator}

  <!-- ===================== METHODOLOGY / E-E-A-T ===================== -->
{methodology}

  <!-- ===================== BEHAVIOUR ===================== -->
  <script>
{calc_js}
  </script>

</div>
"""

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(strip_blank_runs(template), encoding="utf-8")
    size_kb = OUT.stat().st_size / 1024
    print(f"wrote {OUT.relative_to(ROOT)} ({size_kb:.1f} KB)")


if __name__ == "__main__":
    main()
